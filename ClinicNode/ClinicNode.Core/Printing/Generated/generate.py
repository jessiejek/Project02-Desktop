#!/usr/bin/env python3
# JJQR - AI (Nov 21, 2026) - regenerates FormsCss.g.cs (CSS copied verbatim from Project02-fe print-forms-html.ts)
# and FormAssets.g.cs (Project02-fe public/forms/*.png as base64) so the native print forms match the web byte-for-byte.
# Usage:  python3 ClinicNode.Core/Printing/Generated/generate.py   (re-run whenever the web print forms change)
import base64, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
FE = os.path.normpath(os.path.join(HERE, "../../../../../Project02-fe"))
SRC = os.path.join(FE, "src/lib/print-forms-html.ts")
FORMS = os.path.join(FE, "public/forms")

text = open(SRC, encoding="utf-8").read()
lits = re.findall(r"`\n(.*?)(\n?)`;", text, flags=re.S)  # JJQR - AI (Nov 24, 2026): a literal may end on its own last CSS line (no newline before the closing backtick); the 2nd group remembers whether there was one
names = ["ShellCss", "A5LetterheadCss", "MedicalCertificateCss", "PrescriptionCss", "LabRequestCss"]
if len(lits) != len(names):
    sys.exit("expected %d CSS template literals in print-forms-html.ts, found %d" % (len(names), len(lits)))

params = {
    "ShellCss": ["pageSize", "width", "height"],
    "A5LetterheadCss": ["ruleTop"],
}

def method(name, body, trailing_nl="\n"):
    ps = params.get(name, [])
    used = re.findall(r"\$\{(\w+)\}", body)
    for u in used:
        if u not in ps:
            sys.exit("unexpected ${%s} in %s" % (u, name))
    if '"""' in body or "{{" in body or "}}}" in body:
        sys.exit("CSS contains a sequence that breaks the C# raw literal in %s" % name)
    cs_body = re.sub(r"\$\{(\w+)\}", r"{{\1}}", body)
    sig = ", ".join("string " + p for p in ps)
    prefix = "$$" if ps else ""
    tail = ' + "\\n"' if trailing_nl else ""
    return (
        "    public static string %s(%s) => \"\\n\" + %s\"\"\"\n%s\n\"\"\"%s;\n" % (name, sig, prefix, cs_body, tail)
    )

out = ["// JJQR - AI (Nov 21, 2026) - GENERATED by generate.py from Project02-fe/src/lib/print-forms-html.ts. Do not edit by hand.",
       "namespace ClinicNode.Core.Printing;", "", "internal static class FormsCss", "{"]
for n, (b, nl) in zip(names, lits):
    out.append(method(n, b, nl))
out.append("}")
out.append("// JJQR - END")
open(os.path.join(HERE, "FormsCss.g.cs"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")

assets = ["logo.png", "seal.png", "rx.png", "cartoon.png"]
lines = ["// JJQR - AI (Nov 21, 2026) - GENERATED by generate.py from Project02-fe/public/forms/*.png. Do not edit by hand.",
         "namespace ClinicNode.Core.Printing;", "", "public static partial class FormAssets", "{",
         "    static readonly IReadOnlyDictionary<string, string> Base64 = new Dictionary<string, string>", "    {"]
for a in assets:
    data = base64.b64encode(open(os.path.join(FORMS, a), "rb").read()).decode("ascii")
    lines.append('        ["%s"] = "%s",' % (a, data))
lines += ["    };", "}", "// JJQR - END"]
open(os.path.join(HERE, "FormAssets.g.cs"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("wrote FormsCss.g.cs and FormAssets.g.cs")
